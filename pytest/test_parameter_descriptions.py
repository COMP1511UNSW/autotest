# dcc output checking


def dcc(specification):
    t = single_test(specification)
    return t["dcc_output_checking"], {
        k: v for k, v in t["environment"].items() if k.startswith("DCC_")
    }


def test_dcc_output_checking_is_enabled_for_a_simple_c_test_and_sets_dcc_variables():
    enabled, variables = dcc("files=a.c\nt command=./a expected_stdout=hi\n")
    assert enabled is True
    assert variables == {
        "DCC_EXPECTED_STDOUT": "hi",
        "DCC_IGNORE_CASE": "False",
        "DCC_COMPARE_ONLY_CHARACTERS": "",
        "DCC_IGNORE_CHARACTERS": "",
        "DCC_IGNORE_TRAILING_WHITE_SPACE": "True",
        "DCC_IGNORE_WHITE_SPACE": "False",
        "DCC_IGNORE_BLANK_LINES": "False",
        "DCC_MAX_STDOUT_BYTES": "10000",
    }


def test_dcc_variables_reflect_comparison_parameters():
    _, variables = dcc(
        "files=a.c\nt command=./a expected_stdout=hi ignore_whitespace=1 ignore_case=1 compare_only_characters=abc\n"
    )
    assert variables["DCC_IGNORE_CASE"] == "True"
    assert variables["DCC_IGNORE_WHITE_SPACE"] == "True"
    assert variables["DCC_COMPARE_ONLY_CHARACTERS"] == "abc"
    assert set(variables["DCC_IGNORE_CHARACTERS"]) == set(" \t\r\x0b\x0c")


