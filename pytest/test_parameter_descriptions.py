def test_print_markdown_lists_each_documented_parameter_once_and_no_hidden_ones(capsys):
    print_markdown()
    lines = capsys.readouterr().out.splitlines()
    assert lines[0] == "<!--- start - autogenerated from parameter_descriptions.py --->"
    assert lines[-1] == "<!--- end - autogenerated from parameter_descriptions.py --->"
    headers = [re.fullmatch(r"\*\*`(\w+)`\*\*( = .*)?", line) for line in lines]
    documented = [m.group(1) for m in headers if m]
    for p in PARAMETER_LIST:
        if isinstance(p, Parameter):
            assert documented.count(p.name) == (
                1 if p.show_in_documentation else 0
            ), p.name
    assert "### Parameters specifying command to be run" in lines


