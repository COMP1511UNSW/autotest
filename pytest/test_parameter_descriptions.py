def compile_commands(compilers, compiler_args=None, program="a"):
    return finalize_compile_commands(
        "compile_commands",
        None,
        {
            "compilers": compilers,
            "compiler_args": compiler_args or [],
            "program": program,
        },
    )


def test_c_compile_without_dash_o_gets_output_named_after_program():
    assert compile_commands([["gcc", "-Wall"]]) == [["gcc", "-Wall", "-o", "a"]]
    assert compile_commands(["gcc -Wall"]) == ["gcc -Wall -o a"]
    assert compile_commands([["dcc"], ["clang"]]) == [
        ["dcc", "-o", "a"],
        ["clang", "-o", "a"],
    ]


def test_c_compile_already_naming_output_or_program_is_left_alone():
    assert compile_commands([["gcc", "-Wall", "-o", "a"]]) == [
        ["gcc", "-Wall", "-o", "a"]
    ]
    assert compile_commands([["gcc", "-Wall", "a"]]) == [["gcc", "-Wall", "a"]]
    assert compile_commands(["gcc -Wall -o a"]) == ["gcc -Wall -o a"]


def test_duplicate_dash_o_from_compiler_args_replaces_the_compilers_one():
    assert compile_commands([["gcc", "-o", "a"]], ["-o", "b", "a.c"]) == [
        ["gcc", "-o", "b", "a.c"]
    ]
    # a string compiler is turned into a list when its -o is removed
    assert compile_commands(["gcc -o a"], ["-o", "b"]) == [["gcc", "-o", "b"]]


def test_compiler_args_are_appended_to_every_compiler():
    assert compile_commands([["gcc", "-Wall"]], ["-o", "b"]) == [
        ["gcc", "-Wall", "-o", "b"]
    ]
    assert compile_commands([["gcc", "-o", "a"]], ["a.c"]) == [
        ["gcc", "-o", "a", "a.c"]
    ]
    assert compile_commands([["javac"]], ["-g"]) == [["javac", "-g"]]


def test_non_c_compilers_get_no_dash_o():
    assert compile_commands([["javac"]]) == [["javac"]]


def test_compile_commands_via_the_pipeline_from_compilers_and_compiler_args():
    t = single_test(
        "files=a.c\nt command=./a compilers=[['gcc','-Wall']] compiler_args=['-o','b','a.c']\n"
    )
    assert t["compile_commands"] == [["gcc", "-Wall", "-o", "b", "a.c"]]
    t = single_test("files=a.c\nt command=./a compilers='gcc -Wall:clang -Wall'\n")
    assert t["compile_commands"] == [
        ["gcc", "-Wall", "-o", "a"],
        ["clang", "-Wall", "-o", "a"],
    ]
    # only compilers whose name contains "cc" or "clang" get the -o convenience
    t = single_test("files=a.cc\nt command=./a\n")
    assert t["compile_commands"] == [["g++", "-Wall"]]


def test_percent_in_compiler_args_is_replaced_by_program():
    t = single_test(
        "files=a.c\nt command=./a compilers=[['gcc']] compiler_args=['-o','%']\n"
    )
    assert t["compile_commands"] == [["gcc", "-o", "a"]]


