def parse(specification, supplied_files_directory=".", **initial):
    initial["supplied_files_directory"] = str(supplied_files_directory)
    tests, _ = parse_string(specification, initial_parameters=initial)
    return tests


def parse_error(specification, supplied_files_directory="."):
    with pytest.raises(SpecificationError) as info:
        parse(specification, supplied_files_directory)
    return str(info.value)


def single_test(specification, supplied_files_directory=".", **initial):
    """the parameters of the single test 't' in specification"""
    return parse(specification, supplied_files_directory, **initial)["t"]


